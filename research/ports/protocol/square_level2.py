# Square with virtual grid points (mixtures of corners via A.8); maximise weighted diagonals under level-1 crossing on all points.
import numpy as np, itertools, sys
from scipy.optimize import minimize
g=int(sys.argv[1])          # grid g x g points per side (g=2: corners only; g=3: +midpoints+center; g=5 ...)
NPH=int(sys.argv[2]); wp,wq=float(sys.argv[3]),float(sys.argv[4])
pts=[(i,j) for i in range(g) for j in range(g)]
P=len(pts); idx={p:k for k,p in enumerate(pts)}
pairs=[(i,j) for i in range(P) for j in range(i+1,P)]
# symmetry group: for wp==wq full D4, else the subgroup preserving each diagonal class: generated by reflections across diagonals + rotation by 180
def act(f): return [idx[f(p)] for p in pts]
m=g-1
gens=[act(lambda p:(p[1],p[0])),act(lambda p:(m-p[1],m-p[0]))]
if wp==wq: gens.append(act(lambda p:(m-p[0],p[1])))
# orbits of pairs
par={pr:pr for pr in pairs}
def find(x):
    while par[x]!=x: par[x]=par[par[x]]; x=par[x]
    return x
for pr in pairs:
    for gperm in gens:
        a,b=gperm[pr[0]],gperm[pr[1]]; q=(min(a,b),max(a,b))
        ra,rb=find(pr),find(q)
        if ra!=rb: par[ra]=rb
reps=sorted(set(find(pr) for pr in pairs)); oid={r:k for k,r in enumerate(reps)}
nv=len(reps)
orb=np.zeros((P,P),dtype=int)
for pr in pairs: orb[pr]=orb[pr[::-1]]=oid[find(pr)]
def D(x):
    M=x[orb]; np.fill_diagonal(M,0); return M
corn=[idx[(0,0)],idx[(m,0)],idx[(m,m)],idx[(0,m)]]   # a,b,c,d
# A.8 upper bounds: point (i,j) = corner (X,Y) with P(X=1)=i/m,P(Y=1)=j/m, monotone coupling via shared uniforms U,V: X=[U<i/m], Y=[V<j/m]
def ub(s,D1,D2):
    C=np.zeros((2,2,2,2))
    for X,Y,X2,Y2 in itertools.product((0,1),repeat=4):
        dx,dy=X!=X2,Y!=Y2
        if dx and dy: C[X,Y,X2,Y2]= D1 if (X==Y) else D2      # (0,0)-(1,1) is diagonal ac =D1 ; (1,0)-(0,1) = bd = D2
        elif dx or dy: C[X,Y,X2,Y2]=s
    U=np.zeros((P,P))
    for a,(i,j) in enumerate(pts):
        for b,(i2,j2) in enumerate(pts):
            lo,hi=sorted((i/m,i2/m)); lo2,hi2=sorted((j/m,j2/m))
            # U uniform: X=X2=1 w.p. lo, differ w.p. hi-lo (then the larger coordinate has X=1), both 0 w.p. 1-hi
            tot=0
            for px,(X,X2) in [(lo,(1,1)),(hi-lo,((1,0) if i>i2 else (0,1))),(1-hi,(0,0))]:
                for py,(Y,Y2) in [(lo2,(1,1)),(hi2-lo2,((1,0) if j>j2 else (0,1))),(1-hi2,(0,0))]:
                    tot+=px*py*C[X,Y,X2,Y2]
            U[a,b]=tot
    return U
phis=np.linspace(0,np.pi/2,NPH+2)[1:-1]; pp=np.cos(phis)[:,None,None]; qq=np.sin(phis)[:,None,None]
# instance orbit reps
pop=list(itertools.combinations(pairs,2))
seen=set(); popr=[]
def img(gp,inst):
    (x,v),(y,u)=inst
    f=lambda a,b:(min(gp[a],gp[b]),max(gp[a],gp[b]))
    A,B=f(x,v),f(y,u); return (A,B) if A<B else (B,A)
# generate group
G=[list(range(P))]; frontier=[list(range(P))]
while frontier:
    new=[]
    for h in frontier:
        for gp in gens:
            c=[gp[h[k]] for k in range(P)]
            if c not in G: G.append(c); new.append(c)
    frontier=new
for inst in pop:
    if inst in seen: continue
    popr.append(inst)
    for gp in G: seen.add(img(gp,inst))
off=~np.eye(P,dtype=bool)
def cons(x):
    M=D(x); out=[]
    Md=np.where(off,np.maximum(M,1e-9),1.0)
    for (xx,v),(y,u) in popr:
        L=pp*M[xx,v]+qq*M[y,u]
        a=(pp*M[xx][None,:,None]+qq*M[y][None,:,None])+(pp*M[v][None,None,:]+qq*M[u][None,None,:])
        b=(pp*M[xx][None,:,None]+qq*M[u][None,:,None])+(qq*M[y][None,None,:]+pp*M[v][None,None,:])
        rs=np.where(off,(L-a)/Md,0).max(axis=(1,2)).clip(0)
        rps=np.where(off,(L-b)/Md,0).max(axis=(1,2)).clip(0)
        out.append(2-rs**2-rps**2)
    return np.concatenate(out)
tri=[(i,j,k) for i,j,k in itertools.permutations(range(P),3) if i<j]
ti=np.array(tri)
def tcons(x):
    M=D(x); return M[ti[:,0],ti[:,2]]+M[ti[:,2],ti[:,1]]-M[ti[:,0],ti[:,1]]
iu=np.triu_indices(P,1)
def mcons(x):
    M=D(x); a,b,c,d=corn
    U=ub(M[a,b],M[a,c],M[b,d])
    return (U-M)[iu]
a,b,c,d=corn
def obj(x):
    M=D(x); return -(wp*M[a,c]+wq*M[b,d])
def norm(x): return D(x)[a,b]-1
print("points",P,"vars",nv,"instances",len(popr),"group",len(G),flush=True)
rng=np.random.default_rng(0)
for st,(D1,D2) in enumerate([(1.7,1.7),(1.45,1.45),(1.9,1.2),(1.2,1.9)]):
    U=ub(1.0,D1,D2); x0=np.array([U[r] for r in reps])
    res=minimize(obj,x0,method='SLSQP',constraints=[{'type':'ineq','fun':cons},{'type':'ineq','fun':tcons},{'type':'ineq','fun':mcons},{'type':'eq','fun':norm}],bounds=[(0,None)]*nv,options={'maxiter':200,'ftol':1e-10})
    M=D(res.x)
    print("start",st,"value wp*D1+wq*D2 = %.5f"%(-res.fun),"D1 %.4f D2 %.4f"%(M[a,c],M[b,d]),"level1 bound %.5f Euler %.5f"%(wp+wq+np.hypot(wp,wq),2*np.hypot(wp,wq)),"mincons %.1e %.1e %.1e"%(cons(res.x).min(),tcons(res.x).min(),mcons(res.x).min()),flush=True)
