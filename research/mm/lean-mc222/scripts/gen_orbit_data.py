#!/usr/bin/env python3
"""Writes MC222/OrbitData.lean: the 432 symmetries (as 8 row masks each: row k of sigma is
the mask M_k with sigma(p)_k = <M_k, p>) and the 72 first-gate representatives.
The data is only a certificate: Lean checks (MC222/Orbit.lean) that each sigma maps the
targets' span into itself and that every plane is mapped onto some representative."""
import itertools, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)

def mats(x):
    A = [[(x >> (2*i+k)) & 1 for k in range(2)] for i in range(2)]
    B = [[(x >> (4+2*k+j)) & 1 for j in range(2)] for k in range(2)]
    return A, B
def unmats(A, B):
    x = 0
    for i in range(2):
        for k in range(2):
            x |= A[i][k] << (2*i+k); x |= B[i][k] << (4+2*i+k)
    return x
def mul(X, Y): return [[(X[i][0] & Y[0][j]) ^ (X[i][1] & Y[1][j]) for j in range(2)] for i in range(2)]
GL2 = [[[e[0], e[1]], [e[2], e[3]]] for e in itertools.product([0,1], repeat=4) if (e[0]&e[3])^(e[1]&e[2])]
def inv(M): return next(X for X in GL2 if mul(M, X) == [[1,0],[0,1]])
def T(M): return [[M[0][0], M[1][0]], [M[0][1], M[1][1]]]
sig = []
for P, Q, R in itertools.product(GL2, repeat=3):
    for tr in (False, True):
        def g(x):
            A, B = mats(x)
            if tr: A, B = T(B), T(A)
            return unmats(mul(mul(P, A), inv(Q)), mul(mul(Q, B), inv(R)))
        rows = [sum(((g(1 << j) >> k) & 1) << j for j in range(8)) for k in range(8)]
        sig.append(rows)
reps = [tuple(map(int, l.split()[:2])) for l in open(os.path.join(here, "plane_orbits.txt"))]
out = ["/-! Certificate data (generated by scripts/gen_orbit_data.py); checked in MC222/Orbit.lean. -/",
       "", "namespace MC222", "",
       "/-- 432 linear maps of `F₂⁸`, each as its 8 row masks. -/",
       "def sigmas : List (List Nat) := ["]
out.append(",\n".join("  [" + ", ".join(map(str, r)) + "]" for r in sig) + "]")
out += ["", "/-- The 72 first-gate representatives `(a, b)` (orbit order of plane_orbits.txt). -/",
        "def reps : List (Nat × Nat) := ["]
out.append(",\n".join(f"  ({a}, {b})" for a, b in reps) + "]")
out += ["", "end MC222", ""]
open(os.path.join(root, "MC222", "OrbitData.lean"), "w").write("\n".join(out))
