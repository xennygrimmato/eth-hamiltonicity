#!/usr/bin/env python3
"""Orbit representatives of first-gate planes for the 2x2 matrix product over F2.

Independent of the Rust code (written separately; the two are compared by count and orbit sizes).
Inputs x = (a11, a12, a21, a22, b11, b12, b21, b22), bit k of an input index = x_k.
Group: generated by (A,B) -> (P A Q^-1, Q B R^-1) for P,Q,R in GL2(F2) and (A,B) -> (B^T, A^T).
A first gate is the product of two linear forms l_a, l_b (a, b = 8-bit coefficient masks);
up to the affine functions it depends only on the plane span{a, b}.  Composing the circuit with a
group element g maps the plane of l_a*l_b to the plane of (l_a o g)*(l_b o g).

Writes plane_orbits.txt: one line "a b orbit_size" per orbit, representative = smallest plane.
"""
import itertools

N = 256


def mats(x):
    A = [[(x >> (2 * i + k)) & 1 for k in range(2)] for i in range(2)]
    B = [[(x >> (4 + 2 * k + j)) & 1 for j in range(2)] for k in range(2)]
    return A, B


def unmats(A, B):
    x = 0
    for i in range(2):
        for k in range(2):
            x |= A[i][k] << (2 * i + k)
            x |= B[i][k] << (4 + 2 * i + k)
    return x


def mul(X, Y):
    return [[(X[i][0] & Y[0][j]) ^ (X[i][1] & Y[1][j]) for j in range(2)] for i in range(2)]


GL2 = []
for e in itertools.product([0, 1], repeat=4):
    M = [[e[0], e[1]], [e[2], e[3]]]
    if (M[0][0] & M[1][1]) ^ (M[0][1] & M[1][0]):
        GL2.append(M)
assert len(GL2) == 6


def inv(M):
    for X in GL2:
        if mul(M, X) == [[1, 0], [0, 1]]:
            return X


def T(M):
    return [[M[0][0], M[1][0]], [M[0][1], M[1][1]]]


# all 432 group elements as maps on input indices
group = []
for P, Q, R in itertools.product(GL2, repeat=3):
    for tr in (False, True):
        def g(x, P=P, Q=Q, R=R, tr=tr):
            A, B = mats(x)
            if tr:
                A, B = T(B), T(A)
            return unmats(mul(mul(P, A), inv(Q)), mul(mul(Q, B), inv(R)))
        group.append([g(x) for x in range(N)])

# truth tables as Python ints
def tt(f):
    return sum(1 << x for x in range(N) if f(x))


def bitx(x, k):
    return (x >> k) & 1


def c(i, j):
    return tt(lambda x: (bitx(x, 2 * i) & bitx(x, 4 + j)) ^ (bitx(x, 2 * i + 1) & bitx(x, 6 + j)))


targets = [c(i, j) for i in range(2) for j in range(2)]
affine = [tt(lambda x: 1)] + [tt(lambda x, k=k: bitx(x, k)) for k in range(8)]


def in_span(basis, v):
    piv = []
    for b in basis:
        for p, w in piv:
            if (b >> p) & 1:
                b ^= w
        if b:
            p = (b & -b).bit_length() - 1
            piv = [(q, w ^ b if (w >> p) & 1 else w) for q, w in piv] + [(p, b)]
    for p, w in piv:
        if (v >> p) & 1:
            v ^= w
    return v == 0


for gm in group:
    assert len(set(gm)) == N
    for t in targets:
        assert in_span(affine + targets, tt(lambda x: (t >> gm[x]) & 1)), "group does not preserve A+T"


def lin_compose(a, gm):
    """coefficient mask of the linear form x -> l_a(g(x))"""
    return sum(((bin(a & gm[1 << k]).count("1") & 1) << k) for k in range(8))
    # (g is linear, so l_a(g(x)) = sum_k x_k l_a(g(e_k)))


for gm in group:  # g is linear: check it
    for x in range(N):
        y = 0
        for k in range(8):
            if (x >> k) & 1:
                y ^= gm[1 << k]
        assert gm[x] == y


def canon(a, b):
    return tuple(sorted((a, b, a ^ b))[:2])


planes = sorted({canon(a, b) for a in range(1, N) for b in range(1, N) if a != b})
assert len(planes) == 10795
seen = set()
orbits = []
for p in planes:
    if p in seen:
        continue
    orb = {canon(lin_compose(p[0], gm), lin_compose(p[1], gm)) for gm in group}
    assert p in orb
    seen |= orb
    orbits.append((p, len(orb)))
assert sum(s for _, s in orbits) == 10795
with open("plane_orbits.txt", "w") as f:
    for (a, b), s in orbits:
        f.write(f"{a} {b} {s}\n")
print(len(orbits), "orbits; sizes", sorted(s for _, s in orbits))
